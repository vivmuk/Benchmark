#!/usr/bin/env python3
"""Build image-benchmark.html comparison page from manifest.json."""
import os, json

SITE = os.path.expanduser("~/.openclaw/workspace/benchmarks/venice-benchmark-site")
OUTDIR = os.path.join(SITE, "assets", "image-benchmark")
manifest = json.load(open(os.path.join(OUTDIR, "manifest.json")))

# Group results: model -> {cat: {file, ok}}
from collections import OrderedDict
models = OrderedDict()
for r in manifest:
    models.setdefault(r["model"], {})[r["cat"]] = r

CATS = ["1-infographic", "2-portrait", "3-ceos"]
CAT_TITLES = {
    "1-infographic": "Infographic — History of Generative AI (watercolor)",
    "2-portrait": "Portrait — Girl in the Sands",
    "3-ceos": "Group — CEOs at a Retreat",
}
CAT_SHORT = {
    "1-infographic": "Infographic",
    "2-portrait": "Portrait",
    "3-ceos": "CEOs",
}

rows = []
for model, cats in models.items():
    cells = []
    for cat in CATS:
        r = cats.get(cat)
        if r and r.get("ok"):
            rel = f"assets/image-benchmark/{r['file']}"
            ar = r.get("aspect_ratio") or "default"
            cells.append(
                f'<figure class="cell">'
                f'<img loading="lazy" src="{rel}" alt="{model} {cat}" aria-label="{model} {CAT_SHORT[cat]}">'
                f'<figcaption>{CAT_SHORT[cat]} <span class="ar">{ar}</span></figcaption>'
                f'</figure>'
            )
        else:
            cells.append(
                f'<figure class="cell fail"><div class="x">✕</div>'
                f'<figcaption>{CAT_SHORT[cat]} — failed</figcaption></figure>'
            )
    rows.append(
        f'<section class="model"><h2 class="mname">{model}</h2>'
        f'<div class="row">{"".join(cells)}</div></section>'
    )

n_ok = sum(1 for r in manifest if r.get("ok"))
n_fail = sum(1 for r in manifest if not r.get("ok"))

html = f"""<!doctype html>
<html lang="en">
<head>
<meta charset="utf-8">
<meta name="viewport" content="width=device-width, initial-scale=1">
<title>Venice Image Model Benchmark — Side-by-Side Comparison</title>
<style>
:root {{
  --teal: #00D4AA;
  --cream: #FEFCF8;
  --indigo: #1A1A2E;
}}
* {{ box-sizing: border-box; }}
body {{
  margin: 0; background: var(--cream); color: var(--indigo);
  font-family: system-ui, -apple-system, "Segoe UI", Roboto, Helvetica, Arial, sans-serif;
}}
header {{
  background: linear-gradient(135deg, var(--indigo), #2a2a4a);
  color: var(--cream); padding: 2.2rem 1.5rem 1.8rem;
  border-bottom: 4px solid var(--teal);
}}
header h1 {{ margin: 0 0 .5rem; font-size: clamp(1.4rem, 3vw, 2.3rem); }}
header p {{ margin: 0; opacity: .82; max-width: 60rem; line-height: 1.5; }}
.meta {{ padding: .8rem 1.5rem; background: #eefaf6; font-size: .9rem; border-bottom: 1px solid #d7eee6; }}
.model {{ padding: 1.2rem 1.5rem; border-bottom: 1px solid #e9e2d6; }}
.mname {{
  font-size: 1.05rem; font-weight: 700; margin: 0 0 .7rem;
  color: var(--indigo); font-family: ui-monospace, SFMono-Regular, Menlo, monospace;
}}
.row {{ display: grid; grid-template-columns: repeat(3, 1fr); gap: 1rem; }}
.cell {{ margin: 0; }}
.cell img {{
  width: 100%; height: auto; border-radius: 8px; display: block;
  box-shadow: 0 2px 10px rgba(0,0,0,.08); background: #f3eee2; aspect-ratio: auto;
}}
.cell figcaption {{
  font-size: .78rem; color: #4a4a5e; margin-top: .35rem; text-align: center;
}}
.cell figcaption .ar {{ color: var(--teal); font-weight: 600; }}
.cell.fail .x {{
  aspect-ratio: 1/1; display: flex; align-items: center; justify-content: center;
  background: #fdecec; color: #c0392b; font-size: 2rem; border-radius: 8px;
}}
footer {{ padding: 2rem 1.5rem; text-align: center; color: #6a6a7a; font-size: .85rem; }}
a {{ color: var(--teal); }}
@media (max-width: 720px) {{
  .row {{ grid-template-columns: 1fr; }}
}}
</style>
</head>
<body>
<header>
  <h1>Venice Image Model Benchmark</h1>
  <p>Three fixed prompts rendered by every text-to-image model in the Venice API, labeled for side-by-side comparison. Prompts are identical across models; aspect ratio follows the best match each model supports.</p>
</header>
<div class="meta"><strong>{len(models)} models</strong> · <strong>{n_ok} images</strong> generated · <strong>{n_fail}</strong> failed · all prompts identical per column</div>
{''.join(rows)}
<footer>Generated by Paridhi · <a href="index.html">← back to BenchmarkViv</a></footer>
</body>
</html>
"""

out = os.path.join(SITE, "image-benchmark.html")
with open(out, "w") as f:
    f.write(html)
print(f"Wrote {out} ({len(html)} bytes, {len(models)} models, {n_ok} ok / {n_fail} fail)")
